"""Slim a skinned glTF binary (.glb) for the browser build.

Keeps one skinned mesh with POSITION / NORMAL / JOINTS_0 / WEIGHTS_0 (drops UVs: the model uses flat colours),
keeps only the named animations, drops animation channels whose values never change from the rest pose,
and repacks the binary buffer tightly. Writes the result as a .glb and as a small JS file that sets
window.<VAR> to the base64 data, so the page also works when opened straight from disk (file:// cannot fetch).

usage: python -I scripts/slim_glb.py <in.glb> <out.glb> <out.js> <VAR> Anim1=alias1 Anim2=alias2 ...
"""
import base64, json, struct, sys

src, out_glb, out_js, var, *anims = sys.argv[1:]
keep = dict(a.split("=", 1) for a in anims)

d = open(src, "rb").read()
jlen = struct.unpack("<I", d[12:16])[0]
J = json.loads(d[20:20 + jlen])
blen = struct.unpack("<I", d[20 + jlen:24 + jlen])[0]
BIN = d[28 + jlen:28 + jlen + blen]

NCOMP = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT4": 16}
CSIZE = {5120: 1, 5121: 1, 5122: 2, 5123: 2, 5125: 4, 5126: 4}
FMT = {5120: "b", 5121: "B", 5122: "h", 5123: "H", 5125: "I", 5126: "f"}

def raw(ai):
    a = J["accessors"][ai]; bv = J["bufferViews"][a["bufferView"]]
    assert "byteStride" not in bv, "interleaved buffers not supported"
    n = a["count"] * NCOMP[a["type"]] * CSIZE[a["componentType"]]
    o = bv.get("byteOffset", 0) + a.get("byteOffset", 0)
    return BIN[o:o + n]

def floats(ai):
    a = J["accessors"][ai]; b = raw(ai)
    return struct.unpack(f"<{len(b) // 4}f", b), NCOMP[a["type"]]

new_acc, new_bv, chunks = [], [], []
def add(ai):
    a = dict(J["accessors"][ai]); b = raw(ai)
    off = sum(len(c) for c in chunks)
    pad = (-off) % 4
    if pad: chunks.append(b"\0" * pad); off += pad
    chunks.append(b)
    new_bv.append({"buffer": 0, "byteOffset": off, "byteLength": len(b)})
    a["bufferView"] = len(new_bv) - 1; a.pop("byteOffset", None)
    new_acc.append(a)
    return len(new_acc) - 1

# mesh
for m in J["meshes"]:
    for p in m["primitives"]:
        p["attributes"] = {k: add(v) for k, v in p["attributes"].items() if k in ("POSITION", "NORMAL", "JOINTS_0", "WEIGHTS_0")}
        if "indices" in p: p["indices"] = add(p["indices"])
for s in J.get("skins", []):
    if "inverseBindMatrices" in s: s["inverseBindMatrices"] = add(s["inverseBindMatrices"])

# animations
nodes = J["nodes"]
REST = {"translation": [0, 0, 0], "rotation": [0, 0, 0, 1], "scale": [1, 1, 1]}
new_anims, dropped, kept = [], 0, 0
for an in J["animations"]:
    if an["name"] not in keep: continue
    samplers, channels = [], []
    for ch in an["channels"]:
        sm = an["samplers"][ch["sampler"]]; path = ch["target"]["path"]
        vals, k = floats(sm["output"])
        rest = nodes[ch["target"]["node"]].get(path, REST[path])
        const = all(abs(vals[i] - rest[i % k]) < 1e-4 for i in range(len(vals)))
        if const: dropped += 1; continue
        kept += 1
        samplers.append({"input": add(sm["input"]), "output": add(sm["output"]), "interpolation": sm.get("interpolation", "LINEAR")})
        channels.append({"sampler": len(samplers) - 1, "target": ch["target"]})
    new_anims.append({"name": keep[an["name"]], "samplers": samplers, "channels": channels})
missing = set(keep) - {a["name"] for a in J["animations"]}
assert not missing, f"animations not found: {missing}"

J["accessors"], J["bufferViews"], J["animations"] = new_acc, new_bv, new_anims
J.pop("images", None); J.pop("textures", None); J.pop("samplers", None)
body = b"".join(chunks); body += b"\0" * ((-len(body)) % 4)
J["buffers"] = [{"byteLength": len(body)}]
js = json.dumps(J, separators=(",", ":")).encode(); js += b" " * ((-len(js)) % 4)
glb = struct.pack("<III", 0x46546C67, 2, 12 + 8 + len(js) + 8 + len(body)) + struct.pack("<II", len(js), 0x4E4F534A) + js + struct.pack("<II", len(body), 0x004E4942) + body
open(out_glb, "wb").write(glb)
open(out_js, "w", encoding="utf-8", newline="\n").write(
    "// Generated by scripts/slim_glb.py from the CC0 Universal Animation Library (Quaternius). Do not edit by hand.\n"
    f"window.{var}='{base64.b64encode(glb).decode()}';\n")
print(f"glb {len(glb)} bytes, js {len(glb) * 4 // 3} bytes; channels kept {kept}, dropped {dropped}; animations {[a['name'] for a in new_anims]}")
